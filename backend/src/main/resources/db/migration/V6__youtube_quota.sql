-- ============================================================================
-- V6: youtube_quota_usage — YouTube Data API v3 일일 write 쿼터 영속 카운터
--
-- 설계 결정:
--   - date PK: 하루 1행. 재시작/크래시 후에도 당일 누적 소모량이 유지된다.
--   - used_units: 당일 소모된 unit 합계. reserve() 시 트랜잭션 내 증가.
--   - 자정 이후 새 날짜 키로 INSERT → 자동 초기화(이전 날짜 행은 audit 용도로 보존).
--   - in-memory 대신 DB 영속을 선택한 근거:
--       · 서버 재시작(배포, 크래시)에도 쿼터 소모 이력이 유지된다.
--       · 10,000u/일 한도 내 ~6건 정책에서 서비스 재시작은 흔한 이벤트이므로
--         in-memory 카운터는 당일 예산을 실제보다 더 넓게 열어줄 위험이 있다.
--       · 단일 행 UPDATE는 비용이 무시할 수준이며 트랜잭션 격리로 동시성도 처리된다.
-- ============================================================================

CREATE TABLE youtube_quota_usage (
    usage_date  DATE    PRIMARY KEY,
    used_units  BIGINT  NOT NULL DEFAULT 0
);
